static uint32_t vk_find_mem_type(VkPhysicalDevice phys, uint32_t type_filter,
                                 VkMemoryPropertyFlags props) {
    VkPhysicalDeviceMemoryProperties mem_props;
    vkGetPhysicalDeviceMemoryProperties(phys, &mem_props);
    for (uint32_t i = 0; i < mem_props.memoryTypeCount; i++) {
        if ((type_filter & (1u << i)) &&
            (mem_props.memoryTypes[i].propertyFlags & props) == props) {
            return i;
        }
    }
    return UINT32_MAX;
}

static bool vk_buf_create(moe_cache_vulkan_device & dev, VkDeviceSize size,
                          VkBufferUsageFlags usage, VkMemoryPropertyFlags props,
                          vk_buf & out) {
    VkBufferCreateInfo bci = {};
    bci.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO;
    bci.size = size;
    bci.usage = usage;
    bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;

    if (vkCreateBuffer(dev.vk_device, &bci, nullptr, &out.buffer) != VK_SUCCESS) {
        return false;
    }

    VkMemoryRequirements mem_req;
    vkGetBufferMemoryRequirements(dev.vk_device, out.buffer, &mem_req);

    const uint32_t type_index =
        vk_find_mem_type(dev.vk_physical, mem_req.memoryTypeBits, props);
    if (type_index == UINT32_MAX) {
        vkDestroyBuffer(dev.vk_device, out.buffer, nullptr);
        out.buffer = VK_NULL_HANDLE;
        return false;
    }

    VkMemoryAllocateInfo mai = {};
    mai.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO;
    mai.allocationSize = mem_req.size;
    mai.memoryTypeIndex = type_index;

    if (vkAllocateMemory(dev.vk_device, &mai, nullptr, &out.memory) != VK_SUCCESS) {
        vkDestroyBuffer(dev.vk_device, out.buffer, nullptr);
        out.buffer = VK_NULL_HANDLE;
        return false;
    }

    if (vkBindBufferMemory(dev.vk_device, out.buffer, out.memory, 0) != VK_SUCCESS) {
        vkFreeMemory(dev.vk_device, out.memory, nullptr);
        out.memory = VK_NULL_HANDLE;
        vkDestroyBuffer(dev.vk_device, out.buffer, nullptr);
        out.buffer = VK_NULL_HANDLE;
        return false;
    }

    out.size = size;
    out.host_visible = (props & VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT) != 0;
    if (out.host_visible) {
        vkMapMemory(dev.vk_device, out.memory, 0, size, 0, &out.mapped);
    }
    return true;
}

static void vk_buf_destroy(moe_cache_vulkan_device & dev, vk_buf & buf) {
    if (buf.buffer) {
        vkDestroyBuffer(dev.vk_device, buf.buffer, nullptr);
        buf.buffer = VK_NULL_HANDLE;
    }
    if (buf.memory) {
        vkFreeMemory(dev.vk_device, buf.memory, nullptr);
        buf.memory = VK_NULL_HANDLE;
    }
    buf.mapped = nullptr;
    buf.size = 0;
    buf.host_visible = false;
}

static bool vk_buf_reserve(moe_cache_vulkan_device & dev, vk_buf & buf,
                           VkDeviceSize required, VkBufferUsageFlags usage,
                           VkMemoryPropertyFlags props) {
    if (buf.size >= required) {
        return true;
    }
    const size_t capacity = moe_cache_growth_capacity((size_t)buf.size, (size_t)required);
    if (capacity == 0) {
        return false;
    }
    vk_buf next;
    if (!vk_buf_create(dev, capacity, usage, props, next)) {
        return false;
    }
    vk_buf_destroy(dev, buf);
    buf = next;
    return true;
}

// Host-memory scratch that the CPU reads back: prefer a cached memory type.
static bool vk_buf_reserve_host(moe_cache_vulkan_device & dev, vk_buf & buf,
                                VkDeviceSize required, VkBufferUsageFlags usage) {
    const VkMemoryPropertyFlags coherent =
        VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT;
    return vk_buf_reserve(dev, buf, required, usage, coherent | VK_MEMORY_PROPERTY_HOST_CACHED_BIT) ||
           vk_buf_reserve(dev, buf, required, usage, coherent);
}

